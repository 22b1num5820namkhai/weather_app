const {test} = require('node:test');
const assert = require('node:assert/strict');
const bcrypt = require('bcrypt');
const {createApp} = require('../server');
const session = require('express-session');
test('registration, login, validation, error handling and static routes', async () => {
 const rows=[]; let unavailable=false; let race=false;
 const db={async query(sql,args){
  if(unavailable) throw new Error('private database detail');
  assert.ok(sql.includes('?'));
  if(sql.startsWith('SELECT')) return [rows.filter(u=>sql.includes('WHERE id') ? u.id===args[0] : u.email===args[0])];
  if(race) throw Object.assign(new Error('private insert detail'),{code:'ER_DUP_ENTRY'});
  rows.push({id:1,first_name:args[0],last_name:args[1],email:args[2],password_hash:args[3]});return [{insertId:1}];
 }};
 const server=createApp(db, { secret: 'test-only-secret-at-least-32-characters', store: new session.MemoryStore() }).listen(0,'127.0.0.1');
 await new Promise(resolve=>server.once('listening',resolve));
 const base=`http://127.0.0.1:${server.address().port}`;
 let cookie='', csrf='', page='';
 const remember = response => { const value=response.headers.get('set-cookie'); if(value)cookie=value.split(';')[0]; return response; };
 const init = async () => { const response=remember(await fetch(base+'/api/csrf',{headers:{Cookie:cookie}}));csrf=(await response.json()).csrfToken; };
 const post=async(route,body)=>remember(await fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':csrf,'X-Page-Token':page,Cookie:cookie},body:JSON.stringify(body)}));
 try {
  assert.equal((await fetch(base+'/api/me')).status,401);
  assert.equal((await post('/api/login',{})).status,403);
  await init();
  const anonymousCookie=cookie;
  const user={first_name:' Test ',last_name:' User ',email:' TEST@example.com ',password:'test-only-password'};
  assert.equal((await post('/api/register',{...user,first_name:[]})).status,400);
  assert.equal((await post('/api/register',{...user,password:'a'.repeat(73)})).status,400);
  assert.equal((await post('/api/register',user)).status,201);
  assert.equal(rows[0].email,'test@example.com'); assert.equal(rows[0].first_name,'Test');
  assert.notEqual(rows[0].password_hash,user.password);assert.ok(await bcrypt.compare(user.password,rows[0].password_hash));
  assert.equal((await post('/api/register',user)).status,409);
  assert.equal((await post('/api/login',{email:user.email,password:'wrong'})).status,401);
  const login=await post('/api/login',user);assert.equal(login.status,200);
  const result=await login.json();assert.equal(result.authenticated,true);assert.equal(result.user.password_hash,undefined);
  assert.notEqual(cookie,anonymousCookie);
  assert.match(login.headers.get('set-cookie'),/HttpOnly/);assert.match(login.headers.get('set-cookie'),/SameSite=Lax/);
  const rotatedCookie=cookie;
  const staleCsrf=await fetch(base+'/api/logout',{method:'POST',headers:{Cookie:rotatedCookie,'X-CSRF-Token':csrf}});
  assert.equal(staleCsrf.status,403);
  assert.equal((await fetch(base+'/api/me',{headers:{Cookie:anonymousCookie}})).status,401);
  assert.equal((await fetch(base+'/api/me',{headers:{Cookie:rotatedCookie+'tampered'}})).status,401);
  csrf=result.csrfToken;
  page=result.pageToken;
  assert.ok(page);
  assert.doesNotMatch(login.headers.get('set-cookie'), /Max-Age|Expires=/);
  assert.equal((await fetch(base+'/api/me',{headers:{Cookie:cookie}})).status,401);
  assert.equal((await fetch(base+'/api/me',{headers:{Cookie:cookie,'X-Page-Token':'incorrect'}})).status,401);
  const savedCookie=cookie;
  const me=await fetch(base+'/api/me',{headers:{Cookie:cookie,'X-Page-Token':page}});assert.equal(me.status,200);assert.equal((await me.json()).user.id,1);
  const badLogout=await fetch(base+'/api/logout',{method:'POST',headers:{Cookie:cookie,'X-CSRF-Token':'wrong'}});assert.equal(badLogout.status,403);
  const logout=await post('/api/logout',{});assert.equal(logout.status,200);assert.match(logout.headers.get('set-cookie'),/Expires=Thu, 01 Jan 1970/);
  assert.equal((await fetch(base+'/api/me',{headers:{Cookie:savedCookie,'X-Page-Token':page}})).status,401);
  await init();
  assert.equal((await post('/api/login',{email:{},password:[]})).status,400);
  race=true;assert.equal((await post('/api/register',{...user,email:'other@example.com'})).status,409);race=false;
  unavailable=true;const failed=await post('/api/register',user);assert.equal(failed.status,500);assert.ok(!(await failed.text()).includes('private'));unavailable=false;
  assert.equal((await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json'},body:'{'})).status,400);
  for(const route of ['/api/test','/api/check-users']) assert.equal((await fetch(base+route)).status,404);
  for(const route of ['/','/register.js','/assets/weather-sky.png']) assert.equal((await fetch(base+route)).status,200);
  assert.equal((await fetch(base+'/.env')).status,404);
 } finally { server.closeAllConnections(); await new Promise(resolve=>server.close(resolve)); }
});
